/*======================================================================
 * main.asm — Entry point for D32 DSP (both Chip 1 and Chip 2)
 *
 * Boot sequence:
 *   1. Hardware reset → interrupt vector table → _start
 *   2. Detect chip identity from FLAG0 pin
 *   3. Initialize SPORT/DMA/SPI (sport_init.asm)
 *   4. Wait for H1S1 boot config (CHAN_MASK, AUX_MASK)
 *   5. Enter main loop: wait for _block_ready, run 32-sample block
 *
 * Block processing (per DMA completion):
 *   For each sample n in [0..31]:
 *     1. Scatter: DMA RX buffer[n] → per-node _rx_slot_* variables
 *     2. Call process chain (all nodes, single sample)
 *     3. Gather: per-node _tx_slot_* variables → DMA TX buffer[n]
 *
 * Ramp counters run at sample rate (frame counts × BLOCK_SIZE).
 * The same binary runs on both chips; chip-specific paths use _chip_id.
 *
 * AUTO-GENERATED by dsp_codegen.py (D32) — infrastructure.
 *======================================================================*/

/* ADSP-21564 system registers */
#define FLAGS_REG   0x08004040    /* FLAGS register (read-only) */
#define FLAG0_BIT   0x00000001    /* FLAG0 pin: 0=Chip1, 1=Chip2 */
#define BLOCK_SIZE  32

.section/dm seg_dmda;

.global _chip_id;
.var _chip_id = 0;                /* 1 = Chip 1 (Input DSP), 2 = Chip 2 (Output DSP) */

/* Boot config received flag */
.var _boot_config_received = 0;

/* Sample index within current block (0..31) */
.global _sample_idx;
.var _sample_idx = 0;


.section/pm seg_pmco;

/* External symbols */
.extern _sport_init;
.extern _block_ready;
.extern _rx_active_buf, _tx_active_buf;
.extern _ic_rx_active_buf, _ic_tx_active_buf;

#if CHIP_ID == 1
.extern _chip1_process_all;
.extern _scatter_chip1, _gather_chip1;
#elif CHIP_ID == 2
.extern _chip2_process_all;
.extern _scatter_chip2, _gather_chip2;
#else
#error "CHIP_ID must be defined as 1 or 2"
#endif

/*----------------------------------------------------------------------
 * _start — Reset entry point
 *----------------------------------------------------------------------*/
.global _start;
_start:
    /* Detect chip identity from FLAG0 hardware strapping pin */
    /* FLAG0 active-low: grounded = Chip 1, floating/high = Chip 2 */
    r0 = dm(FLAGS_REG);
    r2 = FLAG0_BIT;
    r0 = r0 AND r2;
    r1 = 0;
    comp(r0, r1);
    if eq jump (pc, .is_chip1);
    r0 = 2;
    jump (pc, .chip_set);
.is_chip1:
    r0 = 1;
.chip_set:
    dm(_chip_id) = r0;

    /* Initialize SPORT, DMA, SPI, interrupts */
    call _sport_init;

    /* Wait for boot config from H1S1 MCU */
    /* H1S1 sends CHAN_MASK and AUX_MASK via SPI after power-on handshake */
.wait_boot:
    r0 = dm(_boot_config_received);
    r1 = 0;
    comp(r0, r1);
    if eq jump (pc, .wait_boot);

    /* ---- Main loop ---- */
.main_loop:
    idle;                          /* low-power wait for DMA interrupt */

    r0 = dm(_block_ready);
    r1 = 0;
    comp(r0, r1);
    if eq jump (pc, .main_loop);

    /* Clear block-ready flag */
    r0 = 0;
    dm(_block_ready) = r0;

    /* ---- Block processing: 32 samples per block ---- */
#if CHIP_ID == 1

    /* ========== Chip 1 block loop ========== */
.block_chip1:
    r5 = 0;                       /* sample index */
    r6 = BLOCK_SIZE;

.c1_sample_loop:
    dm(_sample_idx) = r5;

    /* Scatter: DMA RX → input slot variables */
    r0 = r5;                      /* sample index arg */
    call _scatter_chip1;

    /* Process all Chip 1 nodes (single sample) */
    call _chip1_process_all;

    /* Gather: output slot variables → IC TX DMA buffer */
    r0 = dm(_sample_idx);         /* reload (process may have clobbered r5) */
    call _gather_chip1;

    r5 = dm(_sample_idx);
    r5 = r5 + 1;
    comp(r5, r6);
    if lt jump (pc, .c1_sample_loop);

    jump (pc, .main_loop);

#elif CHIP_ID == 2

    /* ========== Chip 2 block loop ========== */
.block_chip2:
    r5 = 0;
    r6 = BLOCK_SIZE;

.c2_sample_loop:
    dm(_sample_idx) = r5;

    /* Scatter: IC RX DMA → recv slot variables */
    r0 = r5;
    call _scatter_chip2;

    /* Process all Chip 2 nodes (single sample) */
    call _chip2_process_all;

    /* Gather: output slot variables → DAC TX DMA buffer */
    r0 = dm(_sample_idx);
    call _gather_chip2;

    r5 = dm(_sample_idx);
    r5 = r5 + 1;
    comp(r5, r6);
    if lt jump (pc, .c2_sample_loop);

    jump (pc, .main_loop);

#endif /* CHIP_ID */

_start.end:
