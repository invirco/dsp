def parse_id_list(cell):
    cell = cell.strip().strip('"')
    if not cell:
        return []
    return [x.strip() for x in cell.split(';') if x.strip()]


def parse_params(cell):
    cell = cell.strip().strip('"')
    if not cell:
        return {}
    params = {}
    for pair in cell.split(';'):
        pair = pair.strip()
        if '=' in pair:
            k, v = pair.split('=', 1)
            params[k.strip()] = v.strip()
    return params


def gen_input_tdm(node):
    p = node['params']
    return dedent(f"""\
        /* INPUT_TDM: Read from SPORT{p.get('sport_id','?')} TDM slot {p.get('slot_start','?')} */
        /* DMA fills rx_buf[] automatically — just reference the slot offset */

        .section/dm seg_dmda;
        .var _rx_slot_{node['id']};     /* pointer to DMA rx buffer slot */

        .section/pm seg_pmco;
        .global _{node['id']}_process;
        _{node['id']}_process:
            /* Audio sample available in _rx_slot_{node['id']} after DMA complete */
            /* Copy to channel processing buffer */
            r0 = dm(_rx_slot_{node['id']});
            dm(_buf_{node['id']}) = r0;
            rts;
        _{node['id']}_process.end:
    """)


def gen_gain(node):
    p = node['params']
    return dedent(f"""\
        /* GAIN: Per-channel gain control */
        /* SPI-controllable: page={node['spi_page']} addr={node['spi_addr']} */

        .section/dm seg_dmda;
        .var _gain_coeff_{node['id']} = 1.0;    /* linear gain coefficient (updated via SPI) */
        .var _mute_{node['id']} = {p.get('mute', '0')};
        .var _buf_{node['id']};

        .section/pm seg_pmco;
        .global _{node['id']}_process;
        _{node['id']}_process:
            /* Read input sample */
            r0 = dm(_buf_{node['inputs_str']});

            /* Apply gain (SIMD-capable for stereo pairs) */
            r1 = dm(_gain_coeff_{node['id']});
            f0 = f0 * f1;

            /* Apply mute */
            r2 = dm(_mute_{node['id']});
            comp(r2, r2);    /* test mute flag */
            if eq f0 = 0.0;  /* if mute=0, pass; if mute=1(nonzero), zero output */
            /* TODO: implement clickless mute with ramp */

            dm(_buf_{node['id']}) = r0;
            rts;
        _{node['id']}_process.end:
    """)


