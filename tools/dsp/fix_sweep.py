#!/usr/bin/env python3
"""fix_sweep.py — every float->fixed conversion in the tree, against what
the part actually does (S25-2, swept in S26).

WHY THIS EXISTS

S25 measured `fix` on this core and found it ROUNDS TO NEAREST, TIES TO
EVEN. Three places in this tree said it truncates toward zero, one host
model implemented truncation, and one comment said it saturates on
overflow when the part was already known to wrap. None of that was
caught by a golden bar, and it could not have been: the goldens are
generated by the same models, and S24's five-level probe used only
powers of two, where every rounding rule agrees.

So the exposure is not something a bar finds. It is something an
ENUMERATION finds, and this is the enumeration. It is a static audit,
not a simulation: it reads the sources, resolves each conversion's scale
constant, and decides from float32's own structure whether that
conversion can round at all.

THE ONE PIECE OF ARITHMETIC THE WHOLE SWEEP RESTS ON

A float32 v is an exact integer whenever |v| >= 2**23, because its 24-bit
significand has no bits left below the binary point. Every conversion in
this tree has the shape

    f_scaled = f_param * SCALE          (a float32 multiply)
    r        = fix f_scaled             (the conversion under audit)

so `fix` can only round when |f_scaled| < 2**23. With SCALE = 2**k that
is |f_param| < 2**(23-k), and multiplying a float32 by a power of two is
EXACT (it moves the exponent and leaves the significand alone), so the
only rounding in the whole chain is the `fix` itself.

    scale 2**28  (Q4.28 gain)   exact for |g|   >= 2**-5  = 0.03125  (-30.1 dB)
    scale 2**31  (Q0.31)        exact for |a|   >= 2**-8  = 0.00390625
    scale 2**27  (Q5.27)        exact for |v|   >= 2**-4  = 0.0625
    scale 2**25  (Q6.25 log2)   exact for |v|   >= 2**-2  = 0.25   (1.505 dB)

Below its floor a conversion CAN round, and the error is at most half an
LSB of the target format -- 2**-29 at Q4.28, which is 174 dB below full
scale. That is the honest size of this whole class: it moves stored
words, it does not move audio. What matters is that the MODELS agree with
the part word for word, because a model that disagrees turns every future
bit-exact bar into a false alarm or, worse, a false pass.

WHERE THE SCALE IS NOT A POWER OF TWO the multiply rounds too, and the
conversion is DOUBLY rounded. Three constants in the tree are like this
-- 126.0 (the pan index), 2**31/100 (the parallel-blend percentage) and
the dB->log2 Q6.25 constant -- and they are called out separately,
because a host model of one of those has to reproduce both roundings in
float32 and not just the final one.

USAGE

    python3 fix_sweep.py                  # the sweep, one line per site
    python3 fix_sweep.py --classes        # by class, with the witness plan
    python3 fix_sweep.py --check          # host models vs the part's rule
    python3 fix_sweep.py --summary        # the one-line verdict
"""
import argparse
import os
import re
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'MW', 'D32', 'DSP', 'SHARC', 'src')
CODEGEN = os.path.join(ROOT, 'tools', 'dsp', 'dsp_codegen.py')

# `Rn = FIX Fx` and `Rn = FIX Fx BY Ry`. The BY form scales inside the
# instruction; it is the per-sample signal conversion and is a different
# class from the parameter conversions, which scale with a float multiply.
FIX_RE = re.compile(r'\br(\d+)\s*=\s*fix\s+f(\d+)(?:\s+by\s+(\S+?))?\s*;')
# A 32-bit immediate load, which is how every float constant reaches a
# register on this core, plus the named-constant form the generator emits.
LOAD_RE = re.compile(r'r(\d+)\s*=\s*(?:0x([0-9A-Fa-f]{8})|_C_([A-Z0-9_]+)_)')

F32 = lambda x: struct.unpack('<f', struct.pack('<f', x))[0]


def f32_of_bits(h):
    return struct.unpack('<f', struct.pack('<I', h))[0]


# Named constants the generator emits by symbol rather than by value.
NAMED = {
    'DB2L2Q25': f32_of_bits(0x4AAA152D),
}


# GENERATED assembly under src/. These are dsp_codegen.py's OUTPUT, and
# counting them alongside the templates that emit them counts one emitter
# twice -- once where it is written and once where it landed. The list is
# explicit rather than inferred because a generated file that stops being
# generated must show up as a new site, not disappear from the sweep.
GENERATED_ASM = {
    'shared_kernels.asm', 'pan_law.asm', 'dsp_params.asm',
    'bus_accumulators.asm', 'num_selftest.asm', 'poly_tables_fx.asm',
    'ctl_epoch.asm', 'rtg_fabric.asm', 'geq_tables.asm', 'afb_tables.asm',
    'ramp_engine.asm', 'ramp_tables.asm',
}


def hand_written_asm():
    """Every .asm that a human maintains.

    `chip*/nodes/` is excluded because it is GENERATED -- auditing its 439
    files would count one emitter hundreds of times and would audit the
    output instead of the source. GENERATED_ASM is the same exclusion for
    the generated files that do NOT live under nodes/: `shared_kernels.asm`
    is dsp_codegen.py's own output, and before S26 noticed it the sweep was
    reporting COMP's and TUBE's conversions twice -- and would have grown by
    eleven the moment GATE and FILT joined the shared table, for no change
    in the tree at all."""
    out = []
    for root, _dirs, files in os.walk(SRC):
        if os.sep + 'nodes' in root:
            continue
        for f in files:
            if f.endswith('.asm') and f not in GENERATED_ASM:
                out.append(os.path.join(root, f))
    return sorted(out)


def scan(path):
    """Every conversion site in one file, with the scale that reaches it.

    The scale is the most recent 32-bit immediate load within 12 lines.
    That window is not a heuristic about style, it is the register
    lifetime: this core has no float immediates, so a constant must be
    loaded into a register and used within a handful of instructions or
    it is destroyed by the unified register file (the reason biquad_fx's
    2**27 constant sits in f1 and not in a hoisted register)."""
    lines = open(path).read().split('\n')
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith('*') or stripped.startswith('/*'):
            continue
        m = FIX_RE.search(line)
        if not m:
            continue
        scale = None
        seen = 0
        j = i - 1
        # THE WINDOW COUNTS INSTRUCTIONS, NOT LINES, and that is not
        # tidiness: this tree comments densely, and a raw-line window
        # walks out of the register's lifetime the moment someone writes
        # a paragraph above the conversion. S26 broke its own resolution
        # of bq_headroom.asm that way, by CORRECTING the comment there.
        while j >= 0 and seen < 12:
            ln = lines[j].strip()
            if not ln or ln.startswith('*') or ln.startswith('/*') \
                    or ln.startswith('#') or ln.endswith('*/') \
                    and not LOAD_RE.search(lines[j]):
                j -= 1
                continue
            h = LOAD_RE.search(lines[j])
            if h:
                if h.group(2):
                    scale = f32_of_bits(int(h.group(2), 16))
                else:
                    scale = NAMED.get(h.group(3))
                break
            seen += 1
            j -= 1
        yield dict(file=os.path.relpath(path, ROOT), line=i + 1,
                   by=m.group(3), scale=scale, text=stripped)


def is_pow2(v):
    if v is None or v <= 0:
        return False
    b = struct.unpack('<I', struct.pack('<f', v))[0]
    return (b & 0x007FFFFF) == 0


def log2_int(v):
    return v.bit_length() - 1 if v == int(v) and int(v) > 0 else None


def classify(site):
    """What this site is, and whether `fix` can round in it.

    Four verdicts:

      SIGNAL      the BY form -- a per-sample conversion of audio, where
                  rounding is the DOCUMENTED behaviour (numeric-spec.md:
                  round, not truncate, on every 32-bit store) and the
                  part agreeing with it is a pass, not an exposure.

      DYADIC      a power-of-two scale. The multiply is exact and `fix`
                  is exact above the floor; below the floor it rounds by
                  at most half an LSB of the target format.

      NON_DYADIC  the scale is not a power of two, so the multiply rounds
                  as well and the site is doubly rounded. These are the
                  sites a host model is most likely to get wrong.

      UNRESOLVED  no scale found in the register window -- audited by
                  hand and annotated below.
    """
    if site['by']:
        return 'SIGNAL', None
    s = site['scale']
    if s is None:
        return 'UNRESOLVED', None
    if is_pow2(s):
        k = log2_int(int(s))
        floor = 2.0 ** (23 - k) if k is not None else None
        return 'DYADIC', floor
    return 'NON_DYADIC', None


# Sites whose scale the register window still cannot resolve, audited by
