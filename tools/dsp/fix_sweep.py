def scale_name(site, verdict):
    if verdict == 'SIGNAL':
        return 'signal (BY form)'
    s = site['scale']
    if s is None:
        return 'unresolved'
    if is_pow2(s):
        k = log2_int(int(s))
        return {28: 'Q4.28 gain (x 2**28)', 31: 'Q0.31 (x 2**31)',
                27: 'Q5.27 (x 2**27)', 25: 'Q6.25 log2 (x 2**25)',
                }.get(k, 'x 2**%s' % k)
    if abs(s - 126.0) < 1e-6:
        return 'pan index (x 126.0)'
    if abs(s - 21474836.0) < 1.0:
        return 'percent -> Q0.31 (x 2**31/100)'
    if abs(s - 5573270.5) < 1.0:
        return 'Q6.25 log2 (x 2**25)'
    if abs(s - 6.0) < 1e-6:
        return 'ceil intent (x 6.0)'
    if abs(s - 0.5) < 1e-9:
        return 'half (x 0.5)'
    if abs(s - 1.0) < 1e-9:
        return 'x 1.0 (no scaling)'
    return 'x %r' % s


def collect():
    sites = []
    for f in hand_written_asm() + [CODEGEN]:
        lines = open(f).read().split('\n')
        for s in scan(f):
            v, floor = classify(s)
            ha = hand_audit(s, lines)
            if v == 'UNRESOLVED' or (ha and v != 'SIGNAL'):
                if ha:
                    v, cls, note = ha
                    s['hand'] = note
                    s['verdict'] = v
                    s['class'] = cls
                    s['floor'] = 2.0 ** -5 if 'Q4.28' in cls else floor
                    sites.append(s)
                    continue
            s['verdict'] = v
            s['floor'] = floor
            s['class'] = (scale_name(s, v) if v != 'UNRESOLVED'
                          else 'unresolved')
            sites.append(s)
    return sites


# ---------------------------------------------------------------------------
# The part's rule, as measured, and the host rules it is compared against.
# ---------------------------------------------------------------------------

def fix_part(v):
    """`Rn = FIX Fx` as MEASURED on this core: round to nearest, ties to
    EVEN, inside the 32-bit range.

    This DEFERS to fixed_ref.fix32 rather than carrying a second copy of
    the rule, and in particular it does not invent an out-of-range
    answer. Exactly one overflow point has ever been measured -- the
    float32 2^31 returns 0xFFFFFFFF -- and one point is not a model, so
    fix32 raises instead of guessing and this sweep inherits that. The
    S26 on-part witness measures the overflow behaviour at several
    points; until a rule is measured, none is asserted here."""
    sys.path.insert(0, os.path.join(ROOT, 'tools', 'dsp'))
    import fixed_ref
    return fixed_ref.fix32(v)


def fix_trunc(v):
    """What the tree's comments used to claim: truncation toward zero."""
    return int(v)


def check_host_models():
    """Every host model of a runtime `fix`, against the part's rule, over
    the domain the model is actually reachable on. Returns rows."""
    rows = []

    # 1. pan index -- pan_table._q428 / the index step. ALWAYS fractional.
    sys.path.insert(0, os.path.join(ROOT, 'tools', 'dsp'))
    try:
        import pan_table
        agree = disagree = 0
        for idx in range(pan_table.PAN_POSITIONS):
            p = pan_table.pan_of(idx)
            prod = F32(F32(p) * F32(126.0))
            if pan_table._fix(prod) == fix_part(prod):
                agree += 1
            else:
                disagree += 1
        rows.append(('pan index', 'pan_table._fix', agree, disagree,
                     '127 indices'))
    except Exception as exc:                       # pragma: no cover
        rows.append(('pan index', 'pan_table._fix', 0, 0, 'ERROR %s' % exc))

    # 2. crossfade alpha -- fixed_ref.xfade_alpha_q, over the ramp's OWN
    #    reachable domain (alpha = k/576, k = 0..575; the kernel never
    #    stores alpha >= 1.0).
    try:
        import fixed_ref
        agree = disagree = frac = 0
        for k in range(576):
            a = F32(k / 576.0)
            prod = F32(F32(a) * F32(float(1 << 31)))
            if prod != int(prod):
                frac += 1
            if fixed_ref.xfade_alpha_q(a) == fix_part(prod):
                agree += 1
            else:
                disagree += 1
        rows.append(('crossfade alpha', 'fixed_ref.xfade_alpha_q',
                     agree, disagree,
                     '576 ramp steps, %d of them fractional' % frac))
    except Exception as exc:                       # pragma: no cover
        rows.append(('crossfade alpha', 'fixed_ref.xfade_alpha_q', 0, 0,
                     'ERROR %s' % exc))

    # 3. Q4.28 gain -- fixed_ref.to_q, swept below its exactness floor,
    #    where it is the only place rounding can happen at all.
    try:
        import fixed_ref
        agree = disagree = 0
        for i in range(1, 20001):
            g = F32(i * 2.0 ** -5 / 20000.0)       # 0 .. the floor
            prod = F32(F32(g) * F32(float(1 << 28)))
            if fixed_ref.to_q(g) == fix_part(prod):
                agree += 1
            else:
                disagree += 1
        rows.append(('Q4.28 gain, sub-floor', 'fixed_ref.to_q',
                     agree, disagree, '20000 gains below 2**-5'))
    except Exception as exc:                       # pragma: no cover
        rows.append(('Q4.28 gain, sub-floor', 'fixed_ref.to_q', 0, 0,
                     'ERROR %s' % exc))

    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--classes', action='store_true')
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--summary', action='store_true')
    args = ap.parse_args()

    sites = collect()
    by_class = {}
    for s in sites:
        by_class.setdefault(s['class'], []).append(s)

    exposed = [s for s in sites
               if s['verdict'] == 'NON_DYADIC'
               or (s['verdict'] == 'DYADIC' and s['floor'])]

    if args.classes:
        for cls in sorted(by_class):
            ss = by_class[cls]
            print('%-32s %3d sites' % (cls, len(ss)))
            note = CLASS_NOTES.get(cls)
            if note:
                for ln in _wrap(note, 74):
                    print('    ' + ln)
            print()
    elif args.check:
        print('%-24s %-26s %8s %9s  %s'
              % ('class', 'host model', 'agree', 'disagree', 'domain'))
        bad = 0
        for name, model, ag, dis, dom in check_host_models():
            print('%-24s %-26s %8d %9d  %s' % (name, model, ag, dis, dom))
            bad += dis
        print()
        print('host and part agree on all classes'
              if not bad else 'MISMATCH: %d vectors' % bad)
        return 1 if bad else 0
    elif args.summary:
        n_sig = sum(1 for s in sites if s['verdict'] == 'SIGNAL')
        print('%d conversions swept, %d exposed by one LSB below their '
              'floor, %d per-sample signal conversions, %d classes'
              % (len(sites), len(exposed), n_sig, len(by_class)))
    else:
        for s in sites:
            print('%-46s %5d  %-30s %s'
                  % (s['file'], s['line'], s['class'], s['verdict']))
    return 0


def _wrap(text, width):
    words, line, out = text.split(), '', []
    for w in words:
        if len(line) + len(w) + 1 > width:
            out.append(line)
            line = w
        else:
            line = (line + ' ' + w).strip()
    if line:
        out.append(line)
    return out


if __name__ == '__main__':
    sys.exit(main())
