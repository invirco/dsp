def hand_audit(site, lines):
    """The hand-audited entry for this site, or None."""
    ctx = '\n'.join(lines[max(0, site['line'] - 8):site['line'] + 1])
    for suffix, pat, verdict, cls, note in HAND_AUDITED:
        if not re.search(suffix, site['file']):
            continue
        if re.search(pat, ctx):
            return verdict, cls, note
    return None


