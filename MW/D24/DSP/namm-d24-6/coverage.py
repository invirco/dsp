#!/usr/bin/env python3
"""NAMM-D24-6: the per-board row coverage table, generated from the profiles
(tools/pi/d24_boards.py) and the runner's own classification of the unit's
catalog, so the table and the code cannot disagree.

    python3 coverage.py > coverage.md
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'pi'))
os.environ.setdefault('MATRIX_ADDR_HOME', os.path.join(
    ROOT, 'MW', 'D24', 'DSP', 's138b', 'fixtures'))
os.environ['D24_UNIT'] = 'MW-D24-2'
import d24_boards as BB      # noqa: E402
import d24_runall as RA      # noqa: E402

CATALOG = os.path.join(ROOT, 'MW', 'D24', 'DSP', 's164', 'data',
                       'test-catalog-unit.csv')
RA.LIST_DIR = os.path.join(ROOT, 'MW', 'D24', 'DSP', 's121')


def how(r):
    if r.category == 'auto':
        return 'auto', ', '.join(r.tests)
    if r.category == 'background':
        return 'background', r.step['measure']
    if r.category == 'manual' and r.group == 'M3':
        return 'pedal', 'pedal link'
    if r.category == 'manual':
        return ('patch' if r.group in RA.PATCH_STATIONS else 'panel'), \
            RA.STATION_NAME.get(r.group, r.group)
    if r.reason == RA.PEDAL_GRADED:
        return 'pedal', 'pedal link (relay half)'
    if r.reason in RA.GRADED_ELSEWHERE.values():
        return 'patch', 'mini-jack step'
    return 'NOT RUN', r.reason


def spans(nums):
    nums = sorted(nums)
    out, i = [], 0
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        out.append(str(nums[i]) if i == j else '%d-%d' % (nums[i], nums[j]))
        i = j + 1
    return ', '.join(out)


def classified(pedal):
    """The catalog as a pass classifies it, with the pedal station on or off
    (the P1 profile turns it on, as `d24_runall.main` does)."""
    RA.set_pedal_station(pedal)
    rows, md5 = RA.load_catalog(CATALOG)
    RA.classify(rows)
    return rows, md5


def main():
    rows, md5 = classified(False)
    rows_pedal, _md5 = classified(True)
    RA.set_pedal_station(False)
    print('# NAMM-D24-6 board coverage (generated by coverage.py)')
    print()
    print('Catalog: the unit\'s copy, md5 `%s`, %d rows. Profiles: '
          '`tools/pi/d24_boards.py`. Roles: home = the part is on this '
          'board; link = a connection that crosses it; carrier = run only to '
          'grade another row.' % (md5[:12], len(rows)))
    print()
    print('## Summary')
    print()
    print('| board | rows | auto | panel loop | analog patches | pedal link '
          '| background | not run |')
    print('|---|---|---|---|---|---|---|---|')
    per = {}

    def rows_of(key):
        return rows_pedal if BB.PROFILES[key].get('pedal_station') else rows
    for key in BB.ORDER:
        lines = dict(BB.coverage(rows_of(key)))[key]
        byn = {r.num: r for r in rows_of(key)}
        c = {}
        for num, role, _cat, _reason, _item in lines:
            k = how(byn[num])[0]
            c.setdefault(k, []).append(num)
        per[key] = c
        print('| %s | %d | %d | %d | %d | %d | %d | %d |'
              % (BB.PROFILES[key]['name'], len(lines),
                 len(c.get('auto', [])), len(c.get('panel', [])),
                 len(c.get('patch', [])), len(c.get('pedal', [])),
                 len(c.get('background', [])), len(c.get('NOT RUN', []))))
    print()
    for key in BB.ORDER:
        lines = dict(BB.coverage(rows_of(key)))[key]
        p = BB.PROFILES[key]
        print('## %s (`%s`)' % (p['name'], key))
        print()
        print(p['note'][0].upper() + p['note'][1:] + '.')
        print()
        c = per[key]
        for k, title in (('auto', 'Automatic (no hands)'),
                         ('panel', 'Panel loop (finger and eye)'),
                         ('patch', 'Analog patches (leads)'),
                         ('pedal', 'Pedal link (plug the pedal in)'),
                         ('background', 'Read in the background')):
            if c.get(k):
                print('- **%s:** rows %s' % (title, spans(c[k])))
        print()
        print('| row | item | role | how | detail |')
        print('|---|---|---|---|---|')
        byn = {r.num: r for r in rows_of(key)}
        for num, role, _cat, _reason, item in lines:
            k, det = how(byn[num])
            print('| %d | %s | %s | %s | %s |'
                  % (num, item.replace('|', '/'), role, k,
                     det.replace('|', '/')))
        print()


if __name__ == '__main__':
    main()
