    rts;
_delay_read_interp.end:


/*----------------------------------------------------------------------
 * _delay_tap — Write + read at fixed offset (common delay use case)
 *
 * In:  f0 = input sample
 *      r0 = delay in samples (integer)
 *      i2 → descriptor[4]
 * Out: f0 = delayed output
 * Clobbers: f1–f6, r1–r5, i3
 *----------------------------------------------------------------------*/
.global _delay_tap;
_delay_tap:
    /* Save input and offset */
    dm(_dly_tap_input) = f0;
    r6 = r0;

    /* Write the input */
    call _delay_write;

    /* Read at offset */
    r0 = r6;
    call _delay_read;

    rts;
_delay_tap.end:


