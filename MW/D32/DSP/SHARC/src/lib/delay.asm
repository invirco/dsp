 * delay.asm — Reusable circular-buffer delay line for ADSP-21564 (D32)
 *
 * Provides delay read/write primitives shared by:
 *   - Input channel delay (DELAY nodes)
 *   - Aux / Main / Monitor output delay
 *   - FX_ENGINE echo / chorus / flanger
 *   - Freeverb comb and allpass filters
 *
 * Public entry points:
 *   _delay_write           — Write one sample into circular buffer
 *   _delay_read            — Read one sample at given offset
 *   _delay_read_interp     — Fractional-sample read (linear interpolation)
 *   _delay_tap             — Combined write + read at offset (common case)
 *   _delay_allpass          — Single allpass stage for reverb
 *   _delay_comb_lpf         — Comb filter with lowpass in feedback (Freeverb)
 *
 * Buffer descriptor convention:
 *   Each delay instance uses a 4-word descriptor in DM:
 *     [0] = buffer base address
 *     [1] = buffer length (samples)
 *     [2] = write pointer (index 0..length-1)
 *     [3] = (reserved / feedback coeff for comb/allpass)
 *
 *   i2 → descriptor base on entry; not advanced.
 *
 * AUTO-GENERATED by dsp_codegen.py (D32) — infrastructure.
 *======================================================================*/

