    call _delay_read;      /* f0 = sample[n] */
    f3 = f0;               /* save sample[n] */

    /* Read sample at offset n+1 */
    r0 = r0 + 1;
    /* Clamp to buffer length */
    r2 = dm(i2, 0);       /* base — peek */
    modify(i2, 1);
    r2 = dm(i2, 0);       /* length */
    modify(i2, -1);        /* rewind */
    comp(r0, r2);
    if ge r0 = r0 - r2;
    call _delay_read;      /* f0 = sample[n+1] */

