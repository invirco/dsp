/*----------------------------------------------------------------------
 * _delay_write — Write one sample into circular buffer, advance pointer
 *
 * In:  f0 = sample to write
 *      i2 → descriptor[4]: {base, length, wptr, reserved}
 * Out: write pointer advanced (wrapped)
 * Clobbers: r1–r5, i3
 *----------------------------------------------------------------------*/
.global _delay_write;
_delay_write:
    r1 = dm(i2, 0);       /* base address (peek, no advance) */
    i3 = r1;               /* i3 = buffer base */
    r2 = dm(i2, 1);       /* base — advance to length */
    r2 = dm(i2, 0);       /* length (peek) */
    modify(i2, 1);         /* advance to wptr */
    r3 = dm(i2, 0);       /* wptr */

    /* Write at base + wptr */
    r4 = r1;
    r4 = r4 + r3;         /* absolute address = base + wptr */
    i3 = r4;
    dm(i3, 0) = f0;       /* write sample */

    /* Advance wptr with wrap */
    r3 = r3 + 1;
    comp(r3, r2);
    if ge r3 = r3 - r2;   /* wrap */
    dm(i2, 0) = r3;       /* store updated wptr */

    /* Rewind i2 to descriptor base (-2 positions) */
    modify(i2, -2);

    rts;
_delay_write.end:


/*----------------------------------------------------------------------
 * _delay_read — Read one sample at a given delay offset (integer)
 *
 * In:  r0 = delay offset in samples (0 = most recent write)
 *      i2 → descriptor[4]: {base, length, wptr, reserved}
 * Out: f0 = delayed sample
 * Clobbers: r1–r5, i3
 *----------------------------------------------------------------------*/
.global _delay_read;
_delay_read:
    r1 = dm(i2, 0);       /* base */
    r2 = dm(i2, 1);       /* (skip base), advance */
    r2 = dm(i2, 0);       /* length */
    modify(i2, 1);
    r3 = dm(i2, 0);       /* wptr */
    modify(i2, -2);        /* rewind to base */

    /* read_index = wptr - offset */
    r4 = r3 - r0;
    /* Wrap if negative */
    r5 = 0;
    comp(r4, r5);
    if lt r4 = r4 + r2;   /* add length */

    /* Read from base + read_index */
    r5 = r1 + r4;
    i3 = r5;
    f0 = dm(i3, 0);

    rts;
_delay_read.end:


/*----------------------------------------------------------------------
 * _delay_read_interp — Fractional-sample read (linear interpolation)
 *
 * In:  f0 = delay offset (float, may be fractional)
 *      i2 → descriptor[4]
 * Out: f0 = interpolated sample
 * Clobbers: f1–f6, r0–r5, i3
