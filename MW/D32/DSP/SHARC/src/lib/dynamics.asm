.section/dm seg_dmda;

/* Log₂ polynomial coefficients (minimax fit, |x| in [1,2), error < 2e-6)
 * log2(x) ≈ c4*x⁴ + c3*x³ + c2*x² + c1*x + c0
 * where x is the mantissa in [1,2) and exponent is added separately */
.var _log2_c0 = -3.4436006;
.var _log2_c1 =  5.5765866;
.var _log2_c2 = -4.1509170;
.var _log2_c3 =  1.7134473;
.var _log2_c4 = -0.2958727;

/* Exp₂ polynomial coefficients (minimax on [0,1), error < 2e-6)
 * 2^f ≈ d4*f⁴ + d3*f³ + d2*f² + d1*f + d0, f in [0,1) */
.var _exp2_d0 =  1.0000000;
.var _exp2_d1 =  0.6931472;
.var _exp2_d2 =  0.2402265;
.var _exp2_d3 =  0.0554953;
.var _exp2_d4 =  0.0096707;

/* dB conversion constants */
.var _log2_to_dB = 6.0205999;     /* 20/ln(10) * ln(2) = 20*log10(2) */
.var _dB_to_log2 = 0.1660964;     /* 1 / 6.0206 */

.section/pm seg_pmco;


/*----------------------------------------------------------------------
 * _dyn_fast_log2f — Fast log₂(|x|) approximation
 *
 * In:  f0 = x (positive; caller takes abs)
 * Out: f0 = log₂(x), approximately
 * Clobbers: f1–f8, r1–r3
 *
 * Method: IEEE 754 float32 bit extraction.
 *   log2(x) = exponent + log2(mantissa)
 *   mantissa in [1,2) → polynomial approximation
 *----------------------------------------------------------------------*/
.global _dyn_fast_log2f;
_dyn_fast_log2f:
    /* Extract exponent: (bits >> 23) - 127 */
    r1 = f0;                  /* reinterpret float as int */
    r2 = lshift r1 by -23;   /* arithmetic shift: sign + exponent */
    r3 = 0xFF;
    r2 = r2 AND r3;            /* mask exponent field (8 bits) */
    r3 = 127;
    r2 = r2 - r3;            /* unbias */
    f8 = float r2;           /* exponent as float */

    /* Extract mantissa: clear exponent, set to 127 (=1.0 biased) */
    r3 = 0x007FFFFF;         /* mantissa mask */
    r1 = r1 and r3;          /* isolate mantissa bits */
    r3 = 0x3F800000;         /* 1.0f in IEEE 754 */
    r1 = r1 or r3;           /* mantissa in [1.0, 2.0) */
    f0 = r1;                 /* reinterpret as float */

    /* Polynomial: c4*m⁴ + c3*m³ + c2*m² + c1*m + c0 (Horner) */
    f1 = dm(_log2_c4);
    f2 = f1 * f0;            /* c4*m */
    f1 = dm(_log2_c3);
    f2 = f2 + f1;            /* c4*m + c3 */
    f2 = f2 * f0;            /* (..)*m */
    f1 = dm(_log2_c2);
    f2 = f2 + f1;
    f2 = f2 * f0;
    f1 = dm(_log2_c1);
    f2 = f2 + f1;
    f2 = f2 * f0;
    f1 = dm(_log2_c0);
    f2 = f2 + f1;            /* log2(mantissa) */

    f0 = f8 + f2;            /* exponent + log2(mantissa) */
    rts;
_dyn_fast_log2f.end:


/*----------------------------------------------------------------------
 * _dyn_fast_exp2f — Fast 2^x approximation
 *
 * In:  f0 = x
 * Out: f0 = 2^x, approximately
 * Clobbers: f1–f6, r1–r3
 *----------------------------------------------------------------------*/
.global _dyn_fast_exp2f;
_dyn_fast_exp2f:
    /* Split x into integer part n and fractional part f in [0,1) */
    /* n = floor(x), f = x - n */
    r1 = trunc f0;           /* integer part (toward zero) */
    /* Adjust for negative: if x < 0 and frac != 0, n = n-1 */
    f1 = float r1;
    f2 = f0 - f1;            /* fractional part */
    /* If f < 0, adjust */
    f3 = 0.0;
    comp(f2, f3);
    if ge jump (pc, .exp2_frac_ok);
    r1 = r1 - 1;
    f1 = float r1;
    f2 = f0 - f1;
.exp2_frac_ok:

    /* Polynomial on f: d4*f⁴ + d3*f³ + d2*f² + d1*f + d0 (Horner) */
    f3 = dm(_exp2_d4);
    f4 = f3 * f2;
    f3 = dm(_exp2_d3);
    f4 = f4 + f3;
    f4 = f4 * f2;
    f3 = dm(_exp2_d2);
    f4 = f4 + f3;
    f4 = f4 * f2;
    f3 = dm(_exp2_d1);
    f4 = f4 + f3;
    f4 = f4 * f2;
    f3 = dm(_exp2_d0);
    f4 = f4 + f3;            /* 2^f ≈ polynomial(f) */

    /* Reconstruct: 2^x = 2^n * 2^f
     * 2^n via IEEE exponent: set exponent field to n+127 */
    r3 = 127;
    r2 = r1 + r3;            /* biased exponent */
    r2 = lshift r2 by 23;    /* shift to exponent field */
    f5 = r2;                 /* 2^n as float */
    f0 = f5 * f4;            /* 2^n * 2^f */
    rts;
_dyn_fast_exp2f.end:


/*----------------------------------------------------------------------
 * _dyn_to_dB — Convert linear amplitude to dB
 *
 * In:  f0 = |x| (linear, positive)
 * Out: f0 = 20*log10(|x|) in dB
 * Clobbers: same as _dyn_fast_log2f + f8
 *----------------------------------------------------------------------*/
.global _dyn_to_dB;
_dyn_to_dB:
    call _dyn_fast_log2f;
    f1 = dm(_log2_to_dB);
    f0 = f0 * f1;             /* log2 * 6.0206 = dB */
    rts;
_dyn_to_dB.end:


/*----------------------------------------------------------------------
 * _dyn_from_dB — Convert dB to linear amplitude
 *
 * In:  f0 = dB value
 * Out: f0 = 10^(dB/20) = 2^(dB/6.0206)
 * Clobbers: same as _dyn_fast_exp2f
 *----------------------------------------------------------------------*/
.global _dyn_from_dB;
_dyn_from_dB:
    f1 = dm(_dB_to_log2);
    f0 = f0 * f1;             /* dB → log2 domain */
    call _dyn_fast_exp2f;
    rts;
_dyn_from_dB.end:


/*----------------------------------------------------------------------
 * _dyn_envelope_follow — Peak envelope follower (single sample)
 *
 * In:  f0 = |input| (rectified)
 *      f1 = attack coefficient  (α_a = 1 - exp(-1 / (Fs * T_a)))
 *      f2 = release coefficient (α_r = 1 - exp(-1 / (Fs * T_r)))
 *      f3 = current envelope state
 * Out: f0 = updated envelope
 * Clobbers: f4–f6
 *
 * Algorithm:
 *   if |x| > env: env += attack * (|x| - env)
 *   else:         env += release * (|x| - env)
 *----------------------------------------------------------------------*/
.global _dyn_envelope_follow;
_dyn_envelope_follow:
    f4 = f0 - f3;             /* delta = |x| - env */
    f5 = 0.0;
    comp(f4, f5);
    if gt jump (pc, .env_attack);

    /* Release: delta < 0 (or 0) */
    f6 = f2 * f4;             /* release * delta */
    f0 = f3 + f6;             /* env + release * (|x| - env) */
    rts;

.env_attack:
    f6 = f1 * f4;             /* attack * delta */
    f0 = f3 + f6;             /* env + attack * (|x| - env) */
    rts;
_dyn_envelope_follow.end:


/*----------------------------------------------------------------------
 * _dyn_gain_compute — Compressor/limiter gain in log domain
 *
 * In:  f0 = envelope_dB (level in dB via _dyn_to_dB)
 *      f1 = threshold_dB
 *      f2 = ratio (e.g 4.0 for 4:1)
 *      f3 = knee_dB (soft knee width; 0 = hard knee)
 * Out: f0 = gain reduction in dB (negative or zero)
 * Clobbers: f4–f9
 *
 * Algorithm (hard knee):
 *   if env_dB > threshold:
 *     gain_dB = threshold + (env_dB - threshold) / ratio - env_dB
 *   else:
 *     gain_dB = 0  (no reduction)
 *
 * Soft knee: quadratic blend within ±knee/2 of threshold
 *----------------------------------------------------------------------*/
.global _dyn_gain_compute;
_dyn_gain_compute:
    f4 = f0 - f1;             /* excess = env_dB - threshold */

    /* Check if we're below threshold (no reduction zone) */
    r14 = 0x3F000000;        /* 0.5 IEEE 754 */
    f5 = f3 * f14;            /* half_knee */
    f5 = -f5;                 /* -half_knee */
    comp(f4, f5);
    if le jump (pc, .gc_no_reduction);

    /* Check soft knee region: excess in [-half_knee, +half_knee] */
    r14 = 0x3F000000;        /* 0.5 IEEE 754 */
    f5 = f3 * f14;
    comp(f4, f5);
    if ge jump (pc, .gc_above_knee);

    /* Soft knee region: quadratic interpolation
     * gain_reduction = (1 - 1/ratio) * (excess + half_knee)² / (2 * knee) */
    /* r14 = 0x3F000000 (0.5f) still set from above check */
    f6 = f3 * f14;            /* half_knee */
    f7 = f4 + f6;             /* excess + half_knee */
    f7 = f7 * f7;             /* squared */
    /* factor_a = 1 - 1/ratio  (NR reciprocal of f2=ratio) */
    r10 = 0x40000000;         /* 2.0 IEEE 754 */
    f9 = RECIPS f2;
    f11 = f2 * f9;
    f11 = f10 - f11;
    f9 = f9 * f11;            /* ~16-bit 1/ratio */
    f11 = f2 * f9;
    f11 = f10 - f11;
    f9 = f9 * f11;            /* ~32-bit 1/ratio */
    r8 = 0x3F800000;          /* 1.0 IEEE 754 */
    f8 = f8 - f9;             /* factor_a = 1 - 1/ratio */
    /* denom = 2 * knee, then compute f7 / denom */
    f9 = f3 + f3;             /* 2 * knee */
    f11 = RECIPS f9;          /* NR reciprocal of denom */
    f12 = f9 * f11;
    f12 = f10 - f12;          /* f10 still = 2.0 */
    f11 = f11 * f12;          /* ~16-bit 1/denom */
    f12 = f9 * f11;
    f12 = f10 - f12;
    f11 = f11 * f12;          /* ~32-bit 1/denom */
    f7 = f7 * f11;            /* (excess+half_knee)² / (2*knee) */
    f0 = f8 * f7;             /* gain reduction */
    f0 = -f0;                 /* return as negative dB */
    rts;

.gc_above_knee:
    /* Above knee: full ratio compression */
    /* gain_reduction = excess * (1/ratio - 1) */
    r10 = 0x40000000;         /* 2.0 IEEE 754 */
    f7 = RECIPS f2;           /* NR reciprocal of ratio */
    f11 = f2 * f7;
    f11 = f10 - f11;
    f7 = f7 * f11;            /* ~16-bit 1/ratio */
    f11 = f2 * f7;
    f11 = f10 - f11;
    f7 = f7 * f11;            /* ~32-bit 1/ratio */
    r6 = 0x3F800000;          /* 1.0 IEEE 754 */
    f7 = f7 - f6;             /* (1/ratio - 1) */
    f0 = f4 * f7;             /* excess * (1/ratio - 1), already negative */
    rts;

.gc_no_reduction:
    r0 = 0;                   /* 0.0f = bit pattern 0x00000000 */
    rts;
_dyn_gain_compute.end:


/*----------------------------------------------------------------------
 * _dyn_rms_detect — RMS level detector (single-pole IIR on x²)
 *
 * In:  f0 = input sample
 *      f1 = smoothing coefficient (α = 1 - exp(-1 / (Fs * T_rms)))
 *      f2 = current RMS² state (sum of squares accumulator)
 * Out: f0 = updated RMS² state (take sqrt for RMS; or use dB directly)
 * Clobbers: f3–f5
 *----------------------------------------------------------------------*/
.global _dyn_rms_detect;
_dyn_rms_detect:
    f3 = f0 * f0;             /* x² */
    f4 = f3 - f2;             /* x² - rms² */
    f5 = f1 * f4;             /* α * (x² - rms²) */
    f0 = f2 + f5;             /* rms² + α * (x² - rms²) */
    rts;
_dyn_rms_detect.end:

