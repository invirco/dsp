/*======================================================================
 * biquad.asm — Reusable biquad filter core for ADSP-21564 (D32)
 *
 * Implements Direct Form II Transposed (DF-II-T) biquad:
 *
 *   w1' = b1*x + a1*y + w2
 *   w2' = b2*x + a2*y
 *   y   = b0*x + w1
 *
 * This form is preferred on SHARC because:
 *   1. Only 2 state variables per stage (vs 4 for DF-I)
 *   2. Better numerical behaviour for narrow-band filters in float32
 *   3. Natural for cascading: output feeds input of next stage
 *
 * Public entry points:
 *   _biquad_mono         — single biquad, 1 sample
 *   _biquad_cascade_N    — N-stage cascade, 1 sample
 *   _biquad_block_32     — single biquad, 32-sample block (loop)
 *   _biquad_cascade_block — N-stage cascade, 32-sample block
 *
 * Register conventions (callee uses, caller saves if needed):
 *   Inputs:
 *     f0 = input sample (mono entry) / i4 = input buffer ptr (block)
 *     i0 = coefficients base: [b0, b1, b2, a1, a2] per stage
 *     i1 = state base: [w1, w2] per stage
 *     r4 = stage count (cascade only)
 *     r5 = sample count (block only)
 *   Output:
 *     f0 = output sample (mono) / written to buffer at i5 (block)
 *   Clobbered: f1–f12, r4–r5, i0–i1 advanced past used stages
 *
 * AUTO-GENERATED by dsp_codegen.py (D32) — infrastructure.
 *======================================================================*/

.section/pm seg_pmco;

/*----------------------------------------------------------------------
 * _biquad_mono — Single-stage DF-II-T biquad, one sample
 *
 * In:  f0 = x, i0 → coeffs[5], i1 → state[2]
 * Out: f0 = y, i0 advanced +5, i1 advanced +2
 *----------------------------------------------------------------------*/
.global _biquad_mono;
_biquad_mono:
    /* Load coefficients */
    f1 = dm(i0, 1);       /* b0 */
    f2 = dm(i0, 1);       /* b1 */
    f3 = dm(i0, 1);       /* b2 */
    f4 = dm(i0, 1);       /* a1 */
    f5 = dm(i0, 1);       /* a2 */

    /* Load state */
    f6 = dm(i1, 0);       /* w1 (don't advance yet) */
    f7 = dm(i1, 1);       /* w1 — now advance; i1 → w2 */
    f8 = dm(i1, 0);       /* w2 */

    /* y = b0 * x + w1 */
    f9 = f1 * f0;         /* b0 * x */
    f9 = f9 + f7;         /* + w1 → y */

    /* w1' = b1 * x + a1 * y + w2 */
    f10 = f2 * f0;        /* b1 * x */
    f11 = f4 * f9;        /* a1 * y */
    f10 = f10 + f11;      /* b1*x + a1*y */
    f10 = f10 + f8;       /* + w2 → new w1 */

    /* w2' = b2 * x + a2 * y */
    f11 = f3 * f0;        /* b2 * x */
    f12 = f5 * f9;        /* a2 * y */
    f11 = f11 + f12;      /* → new w2 */

    /* Store state — rewind i1 by 1, write w1, advance, write w2 */
    modify(i1, -1);        /* back to w1 position */
    dm(i1, 1) = f10;      /* w1' */
    dm(i1, 1) = f11;      /* w2' — i1 now past this stage */

    /* Output */
    f0 = f9;              /* y */
    rts;
_biquad_mono.end:


/*----------------------------------------------------------------------
 * _biquad_cascade_N — N-stage cascaded biquad, one sample
 *
 * In:  f0 = x, i0 → coeffs[N*5], i1 → state[N*2], r4 = N
 * Out: f0 = y (output of last stage)
 *      i0 advanced by N*5, i1 advanced by N*2
 *----------------------------------------------------------------------*/
.global _biquad_cascade_N;
_biquad_cascade_N:
    lcntr = r4; do .cascade_loop until lce;
        call _biquad_mono;
        /* f0 now holds this stage's output, feeds next stage */
    .cascade_loop:
    rts;
_biquad_cascade_N.end:


/*----------------------------------------------------------------------
 * _biquad_block_32 — Single biquad over a 32-sample block
 *
 * In:  i4 = input buffer[32], i5 = output buffer[32]
 *      i0 → coeffs[5], i1 → state[2]
 * Out: output written to buffer at i5
 *      i0 NOT advanced (reloaded per sample from saved base)
 *      i1 advanced by 2 (state updated in place)
 *
 * Note: For in-place processing, set i5 = i4.
 *----------------------------------------------------------------------*/
.global _biquad_block_32;
_biquad_block_32:
    /* Save coefficient base for reload each sample */
    r6 = i0;

    r5 = 32;
    lcntr = r5; do .blk_loop until lce;
        i0 = r6;          /* reload coeff pointer */
        /* Reload state pointer to base (rewind) */
        /* State is updated in-place by _biquad_mono and left at end */
        /* So we save & restore i1 base too */
        f0 = dm(i4, 1);   /* read input sample, advance */

        /* Inline single biquad (avoid call overhead in tight loop) */
        f1 = dm(i0, 1);   /* b0 */
        f2 = dm(i0, 1);   /* b1 */
        f3 = dm(i0, 1);   /* b2 */
        f4 = dm(i0, 1);   /* a1 */
        f5 = dm(i0, 1);   /* a2 */
        f6 = dm(i1, 0);   /* peek w1 */
        f7 = f6;           /* w1 */
        f8 = dm(i1, 1);   /* advance past w1 */
        f8 = dm(i1, 0);   /* w2 — don't advance past */

        f9 = f1 * f0;
        f9 = f9 + f7;     /* y = b0*x + w1 */

        f10 = f2 * f0;
        f11 = f4 * f9;
        f10 = f10 + f11;
        f10 = f10 + f8;   /* w1' = b1*x + a1*y + w2 */

        f11 = f3 * f0;
        f12 = f5 * f9;
        f11 = f11 + f12;  /* w2' = b2*x + a2*y */

        modify(i1, -1);
        dm(i1, 1) = f10;  /* w1' */
        dm(i1, 0) = f11;  /* w2' — leave i1 pointing at w2 for next sample */
        modify(i1, -1);   /* rewind i1 to w1 for next sample */

        dm(i5, 1) = f9;   /* write output, advance */
    .blk_loop:

    /* Leave i1 pointing past the state (w1,w2) so caller can chain stages */
    modify(i1, 2);
    rts;
_biquad_block_32.end:


/*----------------------------------------------------------------------
 * _biquad_cascade_block — N-stage cascade over 32-sample block
 *
 * In:  i4 = input buffer[32], i5 = output buffer[32]
 *      i0 → coeffs[N*5], i1 → state[N*2], r4 = N
 * Out: output written via i5
 *
 * Strategy: Process all 32 samples through stage 0, then all 32
 * through stage 1, etc. Uses a temp buffer for ping-pong between
 * stages. Output of final stage goes to i5.
 *----------------------------------------------------------------------*/
.section/dm seg_dmda;
.var _bq_temp_buf[32];    /* scratch for inter-stage ping-pong */

.section/pm seg_pmco;
.global _biquad_cascade_block;
_biquad_cascade_block:
    /* Save parameters */
    r7 = i0;              /* coeff base */
    r8 = i1;              /* state base */
    r9 = i4;              /* input buf */
    r10 = i5;             /* output buf */

    /* For stage 0: input = i4 (original), output = temp */
    /* For stage 1..N-2: input = temp, output = temp (in-place) */
    /* For stage N-1: input = temp, output = i5 (final) */

    r11 = 0;              /* stage counter */

.cascade_blk_loop:
    comp(r11, r4);
    if ge jump (pc, .cascade_blk_done);

    /* Set up coeff + state pointers for this stage */
    i0 = r7;              /* base + stage*5 */
    r12 = r11;
    r13 = 5;
    r12 = r12 * r13 (SSI);  /* stage offset in coeffs */
    m0 = r12;
    modify(i0, m0);
    i1 = r8;
    r12 = r11;
    r12 = lshift r12 by 1;  /* stage offset in state (x2) */
    m0 = r12;
    modify(i1, m0);

    /* Decide input/output buffers */
    r13 = 0;
    comp(r11, r13);
    if eq jump (pc, .first_stage);
    /* Middle or last stage: input = temp */
    i4 = _bq_temp_buf;
    jump (pc, .check_last);
.first_stage:
    i4 = r9;              /* original input */
.check_last:
    r12 = r4;
    r12 = r12 - 1;
    comp(r11, r12);
    if eq jump (pc, .last_stage);
    /* Not last: output = temp */
    i5 = _bq_temp_buf;
    jump (pc, .do_stage);
.last_stage:
    i5 = r10;             /* final output */
.do_stage:
    call _biquad_block_32;

    r11 = r11 + 1;
    jump (pc, .cascade_blk_loop);

.cascade_blk_done:
    rts;
_biquad_cascade_block.end:
