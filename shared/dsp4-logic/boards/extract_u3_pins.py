#!/usr/bin/env python3
"""extract_u3_pins.py -- U3 (LOGIC CPLD) pin -> net tables for check_pins.py.

The two board netlists live outside this repo, so the tables are extracted
once, committed beside this script, and stamped with where they came from:

  rev C:  mx26 docs/d24-netlist-global-pins.csv   (board 'dsp', refdes U3)
  rev D:  invirco/dspcard KiCad netlist export     (ref "U3")

    python3 extract_u3_pins.py revC <d24-netlist-global-pins.csv> <src-label> > u3-pins-revC.csv
    python3 extract_u3_pins.py revD <netlist.net>                <src-label> > u3-pins-revD.csv

Never hand-edit the CSVs: re-extract from the netlist.
"""
import csv
import re
import sys


def from_mx26(path):
    out = {}
    for r in csv.reader(open(path)):
        if len(r) == 5 and r[1] == "dsp" and r[3] == "U3":
            out[int(r[4])] = r[2]
    return out


def from_kicad(path):
    text = open(path).read()
    out = {}
    for m in re.finditer(r'\(net\s+\(code "?\d+"?\)\s+\(name "([^"]*)"\)(.*?)\n\t\t\)',
                         text, re.S):
        for n in re.finditer(r'\(node\s+\(ref "([^"]+)"\)\s+\(pin "([^"]+)"\)', m.group(2)):
            if n.group(1) == "U3":
                out[int(n.group(2))] = m.group(1)
    return out


def main():
    rev, path, label = sys.argv[1:4]
    pins = from_mx26(path) if rev == "revC" else from_kicad(path)
    if sorted(pins) != list(range(1, 145)):
        sys.exit(f"U3 has {len(pins)} pins in {path}, expected 144")
    print(f"# U3 pin -> net, board {rev}. GENERATED by extract_u3_pins.py; do not hand-edit.")
    print(f"# source: {label}")
    w = csv.writer(sys.stdout, lineterminator="\n")
    w.writerow(["pin", "net"])
    for p in range(1, 145):
        w.writerow([p, pins[p]])


if __name__ == "__main__":
    main()
