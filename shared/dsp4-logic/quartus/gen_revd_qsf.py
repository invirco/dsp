#!/usr/bin/env python3
"""gen_revd_qsf.py -- generate the REV D revision's qsf from the rev C one (S173).

The rev C qsf (dsp4_logic.qsf) stays the single hand-maintained pin file
and stays byte-identical. The rev D file is that file plus:

  - TOP_LEVEL_ENTITY dsp4_logic_revd_top, and the two rtl/revd/ sources;
  - every move in ../boards/revd-pin-moves.csv applied to its
    set_location_assignment line (a move whose line is missing, or matches
    twice, is an error -- no silent no-op);
  - BOARD_REV0 on PIN_81 with the weak pull-up ON (open on rev C = 1,
    GND on rev D = 0);
  - a closing note on which rev C comments no longer describe the copper.

    python3 gen_revd_qsf.py            # writes dsp4_logic_revd.qsf
    python3 gen_revd_qsf.py --check    # exit 1 if the committed file is stale

Never hand-edit dsp4_logic_revd.qsf.
"""
import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "dsp4_logic.qsf")
OUT = os.path.join(HERE, "dsp4_logic_revd.qsf")
MOVES = os.path.join(HERE, "..", "boards", "revd-pin-moves.csv")

HEADER = """\
# dsp4_logic_revd.qsf -- REV D revision of the DSP4 LOGIC CPLD (U3).
# GENERATED by gen_revd_qsf.py from dsp4_logic.qsf (the rev C file) and
# ../boards/revd-pin-moves.csv. DO NOT HAND-EDIT: change either source and
# re-run. ../check_pins.py verifies every location below against the rev D
# netlist (../boards/u3-pins-revD.csv).
#
# Same RTL as rev C (dsp4_logic_top, unchanged) under a rev-D-only wrapper
# that reads BOARD_REV0; see ../rtl/revd/. The rev C text follows, with the
# rev D moves applied in place; each changed line is preceded by a
# "# REV D" comment line.
#
"""

FOOTER = """
# ---- REV D: BOARD_REV0 strap (U3.81) ----
#
# Tied to GND on rev D (DSPC stage 2b, kept by L11 Q2); on rev C the pad is
# the single-pin net L1 and reaches nothing. Weak pull-up ON, so the pin
# reads 1 on rev C copper and 0 on rev D. Reported LIVE in the ID knock
# reply as CFG_BITS[11] = 1 when it reads 0 (dsp4_revd_id_tap.v).
set_location_assignment PIN_81 -to board_rev0
set_instance_assignment -name WEAK_PULL_UP_RESISTOR ON -to board_rev0

# ---- REV D: what the rev C comments above no longer say ----
#
# The unassigned-pin list above is the REV C one. On rev D (DSPC-L8d/L8e/
# MOD 12, netlist u3-pins-revD.csv), still unassigned and so reserved as
# tri-stated inputs with weak pull-up by the global assignment:
#   PI_RX2 / PTRX1 -> PIN_6 (was 77), PI_TX2 / PTRX0 -> PIN_8 (was 84),
#   DSPA_RESOUT -> PIN_77 and DSPB_RESOUT -> PIN_85 (MOD 12: each DSP's
#   SYS_RESOUT, new on rev D; read by nothing yet).
# PIN_87 is TEST1 on rev D (rev C: single-pin net C0). PIN_137 is an
# unconnected pad on rev D (the LOGIC_MEMS stub is gone, DSPC-L8e Q5).
# U3 is 5M1270ZT144C4N on rev D too (the MOD 3 move to the 5M570Z was
# SKIPPED in stage 2b), so this file keeps the rev C DEVICE line.
"""


def main():
    moves = [r for r in csv.DictReader(
        (l for l in open(MOVES) if not l.startswith("#")))]
    text = open(SRC).read()

    text = text.replace(
        "set_global_assignment -name TOP_LEVEL_ENTITY dsp4_logic_top\n",
        "# REV D: the rev-D-only wrapper around the unchanged core\n"
        "set_global_assignment -name TOP_LEVEL_ENTITY dsp4_logic_revd_top\n", 1)
    text = text.replace(
        "set_global_assignment -name VERILOG_FILE ../rtl/dsp4_pcm_reframe.v\n",
        "set_global_assignment -name VERILOG_FILE ../rtl/dsp4_pcm_reframe.v\n"
        "# REV D: the two rev-D-only sources\n"
        "set_global_assignment -name VERILOG_FILE ../rtl/revd/dsp4_revd_id_tap.v\n"
        "set_global_assignment -name VERILOG_FILE ../rtl/revd/dsp4_logic_revd_top.v\n", 1)
    if "dsp4_logic_revd_top" not in text or "dsp4_revd_id_tap" not in text:
        sys.exit("rev C qsf no longer has the TOP_LEVEL_ENTITY / VERILOG_FILE lines this edits")

    for m in moves:
        if m["revC_pin"] == "-":
            continue
        pat = re.compile(r"^set_location_assignment PIN_%s\s+-to %s\s*$"
                         % (m["revC_pin"], re.escape(m["port"])), re.M)
        hits = pat.findall(text)
        if len(hits) != 1:
            sys.exit("move %s: %d matching rev C lines (need exactly 1)"
                     % (m["port"], len(hits)))
        text = pat.sub("# REV D: rev C PIN_%s, %s\nset_location_assignment PIN_%s -to %s"
                       % (m["revC_pin"], m["source"], m["revD_pin"], m["port"]), text)

    out = HEADER + text.rstrip("\n") + "\n" + FOOTER
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != out:
            sys.exit("dsp4_logic_revd.qsf is STALE: run gen_revd_qsf.py")
        print("dsp4_logic_revd.qsf: current")
        return
    open(OUT, "w").write(out)
    print("wrote", os.path.relpath(OUT))


if __name__ == "__main__":
    main()
